// Generates supabase/seed.sql from the app's FAKE seed data, so the database and the mock
// stay identical. Run with:  npm run seed:sql
// (Node 22.6+ strips the TypeScript types when importing the .ts seed files.)
import { writeFileSync } from 'node:fs';
import { SEED_RESTAURANTS } from '../src/data/mock/seed/restaurants.ts';
import { SEED_USERS } from '../src/data/mock/seed/users.ts';
import { SEED_VISITS } from '../src/data/mock/seed/visits.ts';

const q = (value) =>
  value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${q(JSON.stringify(value))}::jsonb`;

// Stable uuids for the fake parents, so re-running the seed never duplicates anything.
const userUuid = (id) => {
  const n = SEED_USERS.findIndex((u) => u.id === id) + 1;
  if (n === 0) throw new Error(`Unknown seed user ${id}`);
  return `00000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
};

const lines = [];
const out = (line = '') => lines.push(line);

out(
  '-- GENERATED by scripts/generate-seed-sql.mjs: do not edit by hand. Run: npm run seed:sql',
);
out('-- FAKE DATA: every restaurant, address, and note below is invented.');
out('-- Safe to run more than once.');
out();

out('insert into public.profiles (id, display_name, avatar_emoji, is_seed) values');
out(
  SEED_USERS.map(
    (u) => `  (${q(userUuid(u.id))}, ${q(u.displayName)}, ${q(u.avatarEmoji)}, true)`,
  ).join(',\n'),
);
out('on conflict (id) do nothing;');
out();

out(
  'insert into public.restaurants (id, name, cuisine, neighborhood, address, price_tier, photo_url, description, hours, is_sample, created_at) values',
);
out(
  SEED_RESTAURANTS.map(
    (r) =>
      `  (${q(r.id)}, ${q(r.name)}, ${q(r.cuisine)}, ${q(r.neighborhood)}, ${q(r.address)}, ${r.priceTier}, ${q(r.photoUrl)}, ${q(r.description)}, ${json(r.hours)}, true, ${q(r.createdAt)})`,
  ).join(',\n'),
);
out('on conflict (id) do nothing;');
out();

const attributeRows = SEED_RESTAURANTS.flatMap((r) =>
  Object.entries(r.attributes).map(
    ([key, state]) =>
      `  (${q(r.id)}, ${q(key)}, ${json(state.value)}, ${q(state.lastConfirmedAt)})`,
  ),
);
out(
  'insert into public.restaurant_attributes (restaurant_id, key, value, last_confirmed_at) values',
);
out(attributeRows.join(',\n'));
out('on conflict (restaurant_id, key) do nothing;');
out();

// Deterministic visit ids, derived from the seed id, make the insert idempotent.
const visitUuid = (id) => `md5(${q(`rj-seed-${id}`)})::uuid`;
out(
  'insert into public.visits (id, restaurant_id, user_id, visited_at, food_rating, stress_level, note, photo_url, created_at) values',
);
out(
  SEED_VISITS.map(
    (v) =>
      `  (${visitUuid(v.id)}, ${q(v.restaurantId)}, ${q(userUuid(v.userId))}, ${q(v.visitedAt)}, ${v.foodRating}, ${v.stressLevel}, ${q(v.note)}, ${q(v.photoUrl)}, ${q(v.createdAt)})`,
  ).join(',\n'),
);
out('on conflict (id) do nothing;');
out();

const confirmationRows = SEED_VISITS.flatMap((v) =>
  Object.entries(v.confirmedAttributes).map(
    ([key, value]) => `  (${visitUuid(v.id)}, ${q(key)}, ${json(value)})`,
  ),
);
if (confirmationRows.length) {
  out('insert into public.visit_attribute_confirmations (visit_id, key, value) values');
  out(confirmationRows.join(',\n'));
  out('on conflict (visit_id, key) do nothing;');
}

const path = new URL('../supabase/seed.sql', import.meta.url);
writeFileSync(path, lines.join('\n') + '\n');
console.log(
  `Wrote supabase/seed.sql: ${SEED_RESTAURANTS.length} restaurants, ${attributeRows.length} attributes, ${SEED_VISITS.length} visits`,
);
